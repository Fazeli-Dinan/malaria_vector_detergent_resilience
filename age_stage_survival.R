  geom_point(size = 2.5) +
  facet_wrap(~treatment, nrow = 1, scales = "fixed") +
  scale_color_manual(values = c(
    "Preadult" = "black",
    "Female" = "red",
    "Male" = "blue"
  )) +
  scale_x_continuous(
    breaks = seq(0, 40, by = 10),
    minor_breaks = seq(0, 40, by = 2),
    expand = c(0, 0),
    guide = guide_axis_minor()
  ) +
  scale_y_continuous(
    limits = c(0, 1.1),
    breaks = seq(0, 1.1, by = 0.2),
    minor_breaks = seq(0, 1.1, by = 0.05),
