  labs(
    title = "Age-stage Survival Rate under Different Treatments",
    x = "Age (days)",
    y = "Survival rate",
    color = "Stage"
  ) +
  coord_fixed(ratio = 60 / 1.5) +
  theme_bw(base_size = 14) +
  theme(
    panel.background = element_rect(fill = "white", color = NA),
    plot.background = element_rect(fill = "white", color = NA),
